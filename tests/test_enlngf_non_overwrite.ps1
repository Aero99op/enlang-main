# test_enlngf_non_overwrite.ps1
$ErrorActionPreference = "Stop"
$testDir = Join-Path $PSScriptRoot "temp_test_non_overwrite_ps"
if (Test-Path $testDir) { Remove-Item -Recurse -Force $testDir }
New-Item -ItemType Directory -Path $testDir -Force | Out-Null

$cssFile = Join-Path $testDir "app.css"
$enlngdFile = Join-Path $testDir "app.enlngd"
$enlgfFile = Join-Path $testDir "sample.enlgf"
$outHtml = Join-Path $testDir "out.html"
$enlngfExe = Join-Path $PSScriptRoot "..\enlngf.exe"

# 1. Create a dummy app.css with arbitrary user CSS
Set-Content -Path $cssFile -Value "/* My custom styles */ body { background: red; }"

# 2. Create companion app.enlngd
Set-Content -Path $enlngdFile -Value "primary color is #ff0000;"

# 3. Create .enlgf sample that links app.css
Set-Content -Path $enlgfFile -Value @"
document enlgf:
    head:
        connect design "app.css"
    body:
        h1 "Hello Enlangg"
"@

# 4. Run enlngf build
$errOutput = cmd /c "`"$enlngfExe`" build `"$enlgfFile`" -o `"$outHtml`" 2>&1"
$exitCode = $LASTEXITCODE

Write-Host "Exit Code: $exitCode"
Write-Host "Output: $errOutput"

# 5. Verify non-zero exit code (1)
if ($exitCode -ne 1) {
    Remove-Item -Recurse -Force $testDir
    throw "[FAIL] Expected exit code 1, but got $exitCode"
}

# 6. Verify error message
if ($errOutput -notmatch "Error: Companion file '.*app\.css' already exists and was not generated by Enlangg\. Refusing to overwrite\.") {
    Remove-Item -Recurse -Force $testDir
    throw "[FAIL] Did not match expected refusal error message. Got: $errOutput"
}

# 7. Verify custom app.css is NOT overwritten
$cssContent = Get-Content -Path $cssFile -Raw
if ($cssContent -notmatch "My custom styles") {
    Remove-Item -Recurse -Force $testDir
    throw "[FAIL] app.css was overwritten!"
}

# 8. Test file with old header ("Compiled by Enlangg")
Set-Content -Path $cssFile -Value @"
/**
 * Compiled by Enlangg Sovereign Design Token Engine v5.3.0
 */
body { color: #abcdef; }
"@

$errOutput2 = cmd /c "`"$enlngfExe`" build `"$enlgfFile`" -o `"$outHtml`" 2>&1"
$exitCode2 = $LASTEXITCODE

if ($exitCode2 -ne 1) {
    Remove-Item -Recurse -Force $testDir
    throw "[FAIL] Expected exit code 1 on file with old header, but got $exitCode2"
}

$cssContent2 = Get-Content -Path $cssFile -Raw
if ($cssContent2 -notmatch "#abcdef") {
    Remove-Item -Recurse -Force $testDir
    throw "[FAIL] File with old header was overwritten!"
}

Write-Host "[PASS] test_enlngf_non_overwrite passed successfully for both arbitrary user files and old header files."
Remove-Item -Recurse -Force $testDir
